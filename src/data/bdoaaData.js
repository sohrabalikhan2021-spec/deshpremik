export function getTotalMedals() {
  let gold = 0
  let silver = 0
  let bronze = 0
  let honorable = 0
  let special = 0

  for (const result of ioaaResults) {
    for (const achievement of result.achievements) {
      switch (achievement.type) {
        case 'gold':
          gold++
          break
        case 'silver':
          silver++
          break
        case 'bronze':
          bronze++
          break
        case 'honorable':
          honorable++
          break
        case 'special':
          special++
          break
      }
    }
  }

  return { gold, silver, bronze, honorable, special }
}

export function getYearsOfParticipation() {
  return ioaaResults.length
}

export function getAchievementsByType(type) {
  const achievements = []
  for (const result of ioaaResults) {
    for (const achievement of result.achievements) {
      if (achievement.type === type) {
        achievements.push({ ...achievement, year: result.year, location: result.location })
      }
    }
  }
  return achievements
}

export function getAllCommitteeMembers() {
  const allMembers = []
  for (const key of Object.keys(committees)) {
    for (const member of committees[key].members) {
      allMembers.push({ ...member, committee: committees[key].title })
    }
  }
  return allMembers
}

export function getResultsByYear(year) {
  return ioaaResults.find((r) => r.year === year) || null
}
